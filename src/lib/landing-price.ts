import type { Lang } from "@/lib/i18n";
import { formatTenge } from "@/lib/utils";

/**
 * Цена на посадочной: одна, и в той валюте, на которой написана страница.
 *
 * ── Одна цена вместо «от» (06.09.2026) ────────────────────────────────────
 *
 * До этого дня витрина показывала «от 25 000 ₸» и таблицу двух тарифов. Так
 * было честно и так было хуже: «от» — это обещание, что настоящая цена
 * выяснится позже, и человек либо считает её ловушкой, либо считает по нижней
 * границе и обижается на верхнюю. Показывается верхний тариф, тот самый, по
 * которому работает кабинет с командой. Ошибка в пользу читателя —
 * единственная безопасная сторона: пришедший по этой цифре никогда не узнает
 * потом, что «на самом деле дороже».
 *
 * Нижний тариф никуда не делся, он остаётся в разговоре об оплате. Витрина —
 * не прайс-лист, её работа кончается на «понятно, сколько это стоит».
 *
 * ── Две валюты ────────────────────────────────────────────────────────────
 *
 * Ссылка `podocare.app` стоит в витрине профиля LinkedIn как живой продукт.
 * Тот, кто по ней приходит, — немецкий рекрутёр или технический лид, и
 * «40 000 ₸ в месяц» ему не говорит ничего: ни валюты, ни порядка суммы.
 * Число без понятной валюты работает хуже, чем его отсутствие.
 *
 * Валюта выбирается языком страницы, а язык — кукой выбора или браузером
 * (`public-lang.ts`):
 *
 *   • `ru` и `kk` — те, кто действительно покупает: тенге. Они платят
 *     переводом в тенге, доллар на витрине сбил бы им расчёт;
 *   • `en` и `de` — витрина: доллары.
 */

/**
 * Долларовая цена — своя пара чисел, а не пересчёт тенге по курсу.
 *
 * Сначала здесь стоял курс (456 ₸ за $1), и 40 000 ₸ превращались в «$88». Это
 * арифметически верно и коммерчески бессмысленно: $88 читается как результат
 * конвертации, то есть как цена, которая завтра будет другой. Цена для внешнего
 * рынка — отдельное решение, а не следствие курса тенге, и принимается она в
 * долларах сразу: $90 в месяц, $900 в год.
 *
 * Отношение к месячной то же, что у тенге (10 месяцев за год), поэтому «два
 * месяца в подарок» остаётся правдой в обеих валютах.
 *
 * Числа живут в коде, а не в настройках платформы: тенговые тарифы правит
 * оператор в админ-консоли, потому что их меняют по ходу разговора с клиникой,
 * а долларовая цена — одна на весь внешний рынок и меняется вместе с решением
 * о нём. Если понадобится править её без выкатки — это колонка в
 * `platform_settings` и поле в консоли, ровно как у тенговых.
 */
export const USD_MONTHLY = 90;
export const USD_YEARLY = 900;

/** «$90». Округление до доллара: центы в цене подписки — шум. */
export function formatUsd(value: number) {
  return `$${Math.round(value).toLocaleString("en-US")}`;
}

/** Числа из `public_pricing()` — как их отдаёт база. */
export type PublicPricing = {
  monthly: number | null;
  yearly: number | null;
  teamMonthly: number | null;
  teamYearly: number | null;
};

export type LandingPricing = {
  currency: "kzt" | "usd";
  /** Главная цифра блока — уже отформатированная, с валютой. */
  monthly: string | null;
  /** «или {сумма} за год». */
  yearly: string | null;
  /** Сколько месяцев экономии даёт год. 0 — если выгоды нет или года нет. */
  savingMonths: number;
};

export function landingPricing(lang: Lang, p: PublicPricing): LandingPricing {
  const usd = lang !== "ru" && lang !== "kk";

  // Тенге берутся из командного тарифа — того самого верхнего. Одиночный
  // подставляется, только если командного в настройках нет вовсе: тогда тариф
  // и правда один, и показывать нечего, кроме него.
  const monthlyRaw = usd ? USD_MONTHLY : (p.teamMonthly ?? p.monthly);
  const yearlyRaw = usd ? USD_YEARLY : (p.teamMonthly != null ? p.teamYearly : p.yearly);
  const money = (value: number) => (usd ? formatUsd(value) : formatTenge(value));

  // «Два месяца в подарок» — не лозунг, а вычитание. Если годовой цены нет или
  // она не выгоднее двенадцати месяцев, никакой выгоды и не обещаем.
  const savingMonths =
    monthlyRaw && yearlyRaw && yearlyRaw < monthlyRaw * 12
      ? Math.round((monthlyRaw * 12 - yearlyRaw) / monthlyRaw)
      : 0;

  return {
    currency: usd ? "usd" : "kzt",
    monthly: monthlyRaw != null ? money(monthlyRaw) : null,
    yearly: yearlyRaw != null ? money(yearlyRaw) : null,
    savingMonths,
  };
}
