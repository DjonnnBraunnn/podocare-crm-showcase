import { LANGS, type Lang } from "@/lib/i18n";
import { langFromAcceptLanguage } from "@/lib/accept-language";

/**
 * Язык публичных страниц — посадочной, входа, регистрации.
 *
 * ── Чем он отличается от языка кабинета ───────────────────────────────────
 *
 * У вошедшего язык личный и лежит в членстве: он его однажды выбрал, и
 * спрашивать больше некого и незачем. У того, кто ещё никем у нас не является,
 * аккаунта нет — и до 06.09.2026 единственным источником был заголовок
 * браузера, а изменить выбор было нельзя вовсе. Это ломалось ровно там, где
 * страницу и показывают: немецкий рекрутёр с русской раскладкой в браузере
 * (а таких в Германии полно — эмигранты, коллеги, свои же знакомые) открывал
 * podocare.app по ссылке из LinkedIn и получал русскую стену, из которой не
 * было выхода.
 *
 * Поэтому выбор теперь можно сделать руками, и он живёт в куке. Порядок:
 *
 *   1. кука — человек нажал флаг, это сильнее любых догадок;
 *   2. заголовок `Accept-Language` — та же системная настройка «предпочитаемые
 *      языки», её присылают и телефон, и компьютер;
 *   3. запасной язык — и он разный у посадочной и у остальных, см. ниже.
 *
 * ── Почему запасной язык разный ───────────────────────────────────────────
 *
 * Посадочная — витрина. Её открывают по ссылке из LinkedIn и из карточки
 * Google Play, то есть человек, о котором мы не знаем ничего, скорее читает
 * по-английски, чем по-русски. Запасной для неё — английский.
 *
 * Вход и регистрация — рабочие экраны сегодняшних клиник. Незнакомый заголовок
 * там значит «казахстанский телефон со странной локалью», и английский на этом
 * экране был бы хуже русского, который читают все нынешние кабинеты. Запасной
 * для них остаётся русским.
 *
 * Разница видна только тем, у кого заголовок не совпал ни с одним из четырёх
 * языков: у всех остальных обе развилки дают один ответ.
 */

/**
 * Имя куки с выбранным языком.
 *
 * Не `lang`: имя из одного общего слова на своём домене — это заявка на
 * столкновение с чем угодно, что окажется на нём завтра.
 */
export const PUBLIC_LANG_COOKIE = "podocare-lang";

/** Год. Язык выбирают один раз, и переспрашивать через месяц незачем. */
export const PUBLIC_LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

/**
 * Значение куки — язык или ничего.
 *
 * Именно `null`, а не «русский по умолчанию», как в `asLang`. Разница
 * существенная: `asLang` отвечает на «какой язык показать» и обязан ответить
 * всегда, а здесь вопрос другой — «сделал ли человек выбор». Подменив мусор
 * русским, мы бы объявили выбором то, чего не было, и заголовок браузера
 * перестал бы спрашиваться вовсе.
 */
export function langFromCookie(value: string | null | undefined): Lang | null {
  return value && (LANGS as readonly string[]).includes(value) ? (value as Lang) : null;
}

/** Язык публичной страницы: кука → заголовок браузера → запасной. */
export function publicLangFrom(
  cookie: string | null | undefined,
  acceptLanguage: string | null | undefined,
  fallback: Lang,
): Lang {
  // Кука сильнее заголовка: она и есть «человек нажал флаг», а заголовок —
  // всего лишь догадка о нём.
  return langFromCookie(cookie) ?? langFromAcceptLanguage(acceptLanguage, fallback);
}
