/**
 * Читает выборку целиком, а не первую тысячу строк.
 *
 * PostgREST на проде запущен с `PGRST_DB_MAX_ROWS=1000` — это не наша
 * настройка, а значение из бандла Supabase. Оно означает, что **любой** запрос
 * без явного окна отдаёт максимум тысячу строк и **не сообщает об этом никак**:
 * ни ошибки, ни признака «есть ещё». Для списка на экране это защита от
 * случайного `select *` на всю базу, и работает она правильно. Для всего, что
 * считает итог в памяти — выгрузка, Статистика, Зарплата, счётчики в консоли, —
 * это тихо неверный ответ, и он тем неверней, чем крупнее клиника.
 *
 * Нашлось на первой же настоящей базе: 2967 карточек и 2560 визитов у первого
 * клиента. Выгрузка «отдайте мои данные» отдавала 1000 карточек из 2967 — файл,
 * который выглядит целым и не является им. Это худший вид ошибки в отчётности:
 * не пусто и не ошибка, а правдоподобное меньшее число.
 *
 * Страница обязана иметь однозначный порядок. Без `order` Postgres не обещает,
 * что вторая тысяча строк не повторит часть первой: `limit/offset` без
 * сортировки — это «любые N строк», а не «следующие N».
 *
 * ── Почему страницы спрашиваются пачкой ───────────────────────────────────
 *
 * Раньше читалось строго по очереди: ответ, потом следующий запрос. У базы
 * Аллы это три круга подряд на каждой Статистике, и каждый круг — не «8 мс до
 * базы», а тысяча строк по проводу и разбор JSON. Круги независимы: окно
 * `[1000, 1999]` не зависит от того, что приехало в `[0, 999]`.
 *
 * Спросить вместо этого общее число (`count: "exact"`) — соблазн, но плата
 * неверная: это отдельный `COUNT(*)` по тому же фильтру, то есть ещё один
 * проход по тем же строкам ради числа, которое нужно только для планирования.
 * На выборке в три страницы счёт стоит дороже, чем экономит.
 *
 * Поэтому: первая страница спрашивается одна (её почти всегда и достаточно —
 * у клиники поменьше отчёт в одну страницу и укладывается), а дальше парами.
 * Неполная страница внутри пары означает конец выборки: всё, что за ней, —
 * пустота, и она отбрасывается.
 *
 * Пара, а не пачка пошире, — потому что за скорость платят лишним запросом, и
 * счёт надо вести по случаям, а не «чем шире, тем лучше». Выборка на N страниц
 * стоила N запросов и N кругов; парами она стоит 1+2·⌈(N−1)/2⌉ запросов и
 * 1+⌈(N−1)/2⌉ кругов. Одна страница — один запрос, как и было. Три страницы —
 * те же три запроса, но два круга вместо трёх. Лишний запрос появляется только
 * на чётном числе страниц, и это запрос за окном, где строк уже нет.
 * Пачка из четырёх дала бы на базе Аллы (2967 карточек, три страницы) два
 * лишних прохода по таблице ради одного сэкономленного круга — плохая цена.
 */

type Page<T> = PromiseLike<{ data: T[] | null; error: { message?: string } | null }>;

const PAGE_SIZE = 1000;

/** Предохранитель: 200 тысяч строк — это уже не отчёт, а выгрузка базы целиком. */
const MAX_ROWS = 200_000;

/**
 * Сколько страниц спрашивать разом после первой.
 *
 * Два — по счёту выше. И заодно: каждая страница держит соединение к
 * PostgREST, а их в пуле восемь на всю программу. Пара оставляет запас
 * соседним страницам; пачка пошире ускорила бы Статистику за счёт журнала
 * записей, открытого в этот момент у администратора.
 */
const BATCH = 2;

export async function fetchAllRows<T>(
  page: (from: number, to: number) => Page<T>,
  pageSize: number = PAGE_SIZE,
): Promise<T[]> {
  const rows: T[] = [];

  // Первая страница отдельно: у большинства кабинетов на ней всё и кончается,
  // и платить за пачку из четырёх запросов ради одной страницы незачем.
  const first = await page(0, pageSize - 1);
  if (first.error) {
    console.error("[podocare] fetchAllRows:", first.error);
    return rows;
  }
  if (!first.data || first.data.length === 0) return rows;
  rows.push(...first.data);
  if (first.data.length < pageSize) return rows;

  for (let offset = pageSize; offset < MAX_ROWS; offset += pageSize * BATCH) {
    const windows: Array<[number, number]> = [];
    for (let i = 0; i < BATCH && offset + i * pageSize < MAX_ROWS; i += 1) {
      const from = offset + i * pageSize;
      windows.push([from, from + pageSize - 1]);
    }

    const answers = await Promise.all(windows.map(([from, to]) => page(from, to)));

    // Разбор строго по порядку окон, а не по порядку ответов: строки обязаны
    // лечь в том же порядке, в каком их отсортировала база.
    let done = false;
    for (const { data, error } of answers) {
      if (error) {
        console.error("[podocare] fetchAllRows:", error);
        return rows;
      }
      if (!data || data.length === 0) {
        done = true;
        break;
      }
      rows.push(...data);
      if (data.length < pageSize) {
        done = true;
        break;
      }
    }
    if (done) break;
  }

  return rows;
}
